// Unlike TaskResponse.deadline (a single point in time), a calendar event
// always has both a start and an end — a punctual event (no explicit end
// picked by the user) is stored with endDateTime equal to startDateTime,
// never null, so every event is a well-formed interval (see
// redcheck-backend's CalendarEvent entity).
export interface CalendarEventResponse {
    id: number;
    title: string;
    description: string | null;
    startDateTime: string;
    endDateTime: string;
    allDay: boolean;
    categoryId: number | null;
    // Non-null when this occurrence was generated by a recurring event
    // routine — see RecurringCalendarEventRequest below.
    recurringEventId: number | null;
}

export interface CalendarEventRequest {
    title: string;
    description: string | null;
    startDateTime: string;
    endDateTime: string | null;
    allDay: boolean;
    categoryId: number | null;
}

